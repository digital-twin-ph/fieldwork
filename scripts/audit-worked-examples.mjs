/** THE WORKED-EXAMPLE AUDIT, generated.
 *
 *  The practitioner, 2026-10-29: *"We can actually perform a more exhaustive audit and generate a
 *  document: (1) widget utilization in worked examples (2) worked example generation from scratch
 *  (identifies bespoke components)."*
 *
 *  Two questions, and they are not the same question. The first asks which widgets any workflow
 *  reaches -- a widget a lab check proves RIGHT and no workflow needs has not been shown USEFUL.
 *  The second asks whether an example could be rebuilt by someone who has only what this project
 *  publishes, which is where a bespoke component or a bespoke asset shows up: a widget attached to
 *  one example, or data that exists only inside a workflow file.
 *
 *  Generated, never hand-edited, for the reason the evidence ledger gives: a measurement written
 *  by hand is a measurement of what somebody remembered. Read from the registry the application
 *  itself uses, so an example this build does not carry cannot be silently missed.
 *
 *  Usage: node scripts/audit-worked-examples.mjs [--write]
 */
import {readFileSync,writeFileSync} from 'node:fs';
import {WORKED_EXAMPLE_KEYS,EXAMPLE_TEMPLATES} from '../build/example-templates.js';

const root=new URL('..',import.meta.url).pathname.replace(/\/$/,'');
const read=path=>JSON.parse(readFileSync(`${root}/${path}`,'utf8'));
const today=new Date().toISOString().slice(0,10);

const shipped=WORKED_EXAMPLE_KEYS.flatMap(key=>{
  try{return [[key,EXAMPLE_TEMPLATES[key]()]];}catch{return [];}
});
const evidence=read('widgets/evidence.json');
const standardization=read('widgets/standardization.json');
const pinned=read('widgets/examples.json').examples??[];

/** A widget attached by NAME to one example is the admission failure D2 and the standardization
 *  ledger both watch for. Read from the ledger rather than guessed from a title. */
const attached=new Map([...(standardization.exempt??[]),...(standardization.deferred??[])]
  .map(entry=>[entry.nodeType,entry.disposition??'declared']));

/** Data a workflow file carries inside itself. A worked example has to carry SOMETHING or it
 *  would not open, so the question is never whether a payload is there -- it is whether the
 *  payload says where it came from. A node that declares `sourceInfo` or `provenance` can be
 *  rebuilt by fetching what it names; one that declares neither can be rebuilt only by copying
 *  this file, which is the definition of a bespoke asset. */
const PAYLOAD=['data','geometry','image','plate','table','rows','features'];
const payloadOf=node=>PAYLOAD.filter(key=>{
  const held=node.params?.[key];
  if(!held)return false;
  if(Array.isArray(held))return held.length>0;
  if(typeof held==='object')return Object.keys(held).length>0;
  return typeof held==='string'&&held.length>64;   // a data: URI, not a label
});
const declares=node=>!!(node.params?.sourceInfo||node.params?.provenance);

const perExample=shipped.map(([key,workflow])=>{
  const types=[...new Set(workflow.nodes.map(n=>n.type))];
  const carrying=workflow.nodes.filter(n=>payloadOf(n).length);
  return {key,name:workflow.name,nodes:workflow.nodes.length,types,
    carrying:carrying.length,
    declared:carrying.filter(declares).length,
    // A DRAWN EXTENT IS NOT THE SAME KIND OF THING AS A DATASET. Both are payloads carried in
    // the file, and only one of them needs a published input: a study area is reproduced by
    // drawing one, and the sized-box control makes that an entry rather than a tracing. The
    // exact coordinates are still a choice nobody else can derive, so it is reported -- but
    // separately, because calling it a bespoke asset would put "the practitioner drew a box"
    // in the same column as "this data exists nowhere else".
    undeclared:carrying.filter(n=>!declares(n)&&n.type!=='study_area').map(n=>`${n.id} (${n.type})`),
    drawnExtents:carrying.filter(n=>!declares(n)&&n.type==='study_area').length,
    attachedTypes:types.filter(t=>attached.has(t))};
});

const sole=new Map();
for(const widget of evidence.widgets)
  if(widget.exampleUseCount===1)sole.set(widget.nodeType,widget.exampleUses[0]);
const unused=evidence.widgets.filter(w=>!w.exampleUseCount).map(w=>w.nodeType);

const row=cells=>`| ${cells.join(' | ')} |`;
const lines=[];
lines.push('# Worked-example audit: what the examples exercise, and what only they carry','',
  `_Created 2026-10-29 · Updated ${today}_`,'',
  'Generated by `scripts/audit-worked-examples.mjs` from the example registry the application',
  'itself uses, `widgets/evidence.json`, `widgets/examples.json` and `widgets/standardization.json`.',
  'Never hand-edited.','',
  'Two questions, and they are not the same. **Utilization** asks which widgets a workflow reaches:',
  'a lab check establishes that a widget is right, and appearing in a workflow is the only evidence',
  'here that it is useful. **Reconstructability** asks whether someone holding only what this',
  'project publishes could rebuild an example — which is where a bespoke component or a bespoke',
  'asset shows up.','');

lines.push('## 1 · Widget utilization','',
  `${evidence.widgets.length} live widgets across ${shipped.length} shipped examples and `
  +`${pinned.length} pinned in its own repository.`,'',
  row(['Reach','Widgets']),row(['---','---']),
  row(['Used by no workflow',`**${unused.length}**`]),
  row(['Used by exactly one',`${sole.size}`]),
  row(['Used by two or more',`**${evidence.widgets.length-unused.length-sole.size}**`]),'',
  '`isochrone` and `compute_walking_catchment` are a special case the practitioner ruled on',
  '2026-10-29: use of the monolith is use of its components. Four of the unused names below are',
  'its members, so they are not unexercised in function. Left uncounted rather than quietly',
  'fixed — see experiment 64.','',
  '### Used by no workflow','',unused.map(t=>`- \`${t}\``).join('\n'),'',
  '### Used by exactly one workflow','',
  'Each of these has one workflow\'s worth of evidence. If that example changes, it has none.','',
  row(['Widget','Its only example']),row(['---','---']),
  ...[...sole].sort((a,b)=>a[1].localeCompare(b[1])||a[0].localeCompare(b[0]))
    .map(([type,example])=>row([`\`${type}\``,example])),'');

const byExample=new Map();
for(const [type,example] of sole)byExample.set(example,[...(byExample.get(example)??[]),type]);
// USED ACROSS EXAMPLES. The practitioner, 2026-10-29: *"We should also track which widgets are
// used across examples, those are genuinely emerging as useful widgets."* The count above said
// how many and never said which, which is the half that can act on anything: a widget two
// unrelated problems both needed is the strongest evidence of usefulness this project collects,
// and it is a different claim from being used a lot inside one example.
const across=evidence.widgets.filter(w=>w.exampleUseCount>1)
  .sort((a,b)=>b.exampleUseCount-a.exampleUseCount||a.nodeType.localeCompare(b.nodeType));
lines.push('### Used across examples — emerging as genuinely useful','',
  'A widget two unrelated problems both needed is the strongest evidence of usefulness this',
  'project collects. It is a different claim from being used heavily inside one example, which is',
  'evidence about that example.','',
  row(['Widget','Examples','Which']),row(['---','---:','---']),
  ...across.map(w=>row([`\`${w.nodeType}\``,w.exampleUseCount,w.exampleUses.join(', ')])),'',
  '**Read the bottom of that table with care.** Two examples of the SAME study are weaker evidence',
  'than two unrelated ones, and `clip_polygons`, `reproject` and `summarize_points_to_polygon` each',
  'reach exactly two: `snow-isochrone` and `snow-voronoi`, which are two questions about one',
  'outbreak in one place. They have crossed an example boundary without crossing a problem. The',
  'rows above `case_series` are the ones that have genuinely done both.','');

lines.push('### Which example is carrying the evidence','',
  row(['Example','Widgets it is the sole user of']),row(['---','---']),
  ...[...byExample].sort((a,b)=>b[1].length-a[1].length)
    .map(([example,types])=>row([example,`**${types.length}** — ${types.map(t=>`\`${t}\``).join(', ')}`])),
  '','A high number here is a fragility rather than a strength: that example is the only thing',
  'standing between those widgets and no evidence at all.','');

lines.push('## 2 · Generation from scratch','',
  'The test the practitioner set on 2026-10-29: *"I should be able to download all the input data,',
  'start from a blank canvas and recreate the example from scratch."* Three things have to hold.',
  'No widget attached to the example, every input obtainable, every parameter reachable from its',
  'own panel.','',
  '**A bespoke asset is a node that carries a payload and declares no source.** Every worked',
  'example carries data or it would not open; the question is whether the node says where that',
  'data came from, because a node that names its source can be rebuilt by fetching it and a node',
  'that does not can be rebuilt only by copying this file.','',
  row(['Example','Nodes','Carry data','Declare a source','Data with no source','Drawn extents','Attached widgets']),
  row(['---','---:','---:','---:','---','---:','---']),
  ...perExample.map(e=>row([`\`${e.key}\``,e.nodes,e.carrying,e.declared,
    e.undeclared.length?`**${e.undeclared.length}** — ${e.undeclared.join(', ')}`:'—',
    e.drawnExtents||'—',
    e.attachedTypes.length?e.attachedTypes.map(t=>`\`${t}\``).join(', '):'—'])),'');

// HOW FINISHED EACH EXAMPLE IS, as four conditions rather than an impression. The practitioner,
// 2026-10-29: *"Many examples are half baked."* That is a judgement worth turning into a number,
// because "half baked" and "small" are different things -- an example can be four nodes and
// complete, or eighteen and unfinished -- and because an example nobody can rebuild is the one
// kind of incompleteness this project has decided it cares about.
//
// The conditions are the ones the practitioner already set, not new ones invented here: every
// data-carrying node names its source, no widget is attached to it by name, its inputs are
// published as files a reader can download, and a rebuild from an empty canvas exists as a test.
const rebuildTest='tests/recreate-from-scratch.browser.mjs';
const rebuilt=(()=>{try{return readFileSync(`${root}/${rebuildTest}`,'utf8');}catch{return '';}})();
const maturity=perExample.map(e=>{
  const met=[
    ['sources',!e.undeclared.length],
    ['unattached',!e.attachedTypes.length],
    // A shipped example's inputs live in this repository's own source, not as files a reader
    // fetches. Only the pinned example publishes them, which is why it is the only one that can
    // meet this today -- stated rather than scored away.
    ['published files',false],
    ['rebuilt from scratch',rebuilt.includes(e.key)],
  ];
  return {...e,met,score:met.filter(([,ok])=>ok).length};
});
const totalUndeclared=perExample.reduce((n,e)=>n+e.undeclared.length,0);
const totalDrawn=perExample.reduce((n,e)=>n+e.drawnExtents,0);
lines.push(`Across the shipped examples, **${totalUndeclared} nodes carry data and declare no `
  +`source**. That is the list a from-scratch rebuild would have to copy rather than fetch. A `
  +`further ${totalDrawn} study areas carry a drawn geometry with no declared source; those are `
  +`redrawn rather than fetched, which the sized-box control makes an entry rather than a tracing.`,'',
  '### What this cannot establish','',
  '- **That a declared source resolves.** This reads whether `sourceInfo` or `provenance` is',
  '  present, not whether the URL answers or the digest matches. `validate:examples` checks the',
  '  pinned bundle\'s digests; nothing checks a shipped example\'s declared source.',
  '- **That every parameter is reachable from its panel.** Only a rebuild can show that, and only',
  '  one exists: `tests/recreate-from-scratch.browser.mjs` builds `south-london/ground` from an',
  '  empty canvas and the published files. The other five South London workflows and all',
  `  ${shipped.length} shipped examples are unproven on this point.`,
  '- **That a published input could be DERIVED in the application.** See the two claims below,',
  '  which is where this belongs rather than in a list of caveats.',
  '- **That an unused widget should be retired.** D11 asks whether a residual function remains',
  '  that nothing else performs. A widget may be unused because no example poses its problem yet,',
  '  which is a gap in the examples rather than in the palette.','',
  '### How finished each example is','',
  'The practitioner, 2026-10-29: *"Many examples are half baked."* Four conditions, none of them',
  'invented here — every data-carrying node names its source, no widget is attached to the example',
  'by name, the inputs are published as files a reader can download, and a rebuild from an empty',
  'canvas exists as a test. Node count is shown beside them because small and unfinished are',
  'different things: an example can be four nodes and complete, or eighteen and not.','',
  row(['Example','Nodes','Conditions met','Missing']),row(['---','---:','---:','---']),
  ...[...maturity].sort((a,b)=>b.score-a.score||b.nodes-a.nodes).map(e=>row([
    `\`${e.key}\``,e.nodes,`${e.score} / 4`,
    e.met.filter(([,ok])=>!ok).map(([name])=>name).join(', ')||'—'])),
  row(['`south-london-1854` (pinned)','—','**3 / 4**','rebuilt from scratch: 1 of its 6 workflows']),
  '',
  'No shipped example meets more than two, and every one of them fails on published inputs for the',
  'same structural reason: a shipped example\'s data lives in this repository\'s source rather than',
  'as files a reader fetches. Only the pinned example publishes its inputs, which is what made a',
  'from-scratch rebuild possible for it and impossible for the rest. That is one decision, not',
  'eleven oversights — and it is the decision to revisit if more examples are to become robust.','',
  '### Two claims, two starting points','',
  'The practitioner drew the distinction on 2026-10-29, and it is the one this section turns on:','',
  '> For the from scratch claim, if the Thames polygons are provided, the end to end claim holds.',
  '> But if the start begins from PBF download, that may well be a different story if Thames',
  '> selection is bespoke.','',
  'Both are called "from scratch" and they are not the same claim.','',
  row(['','Starts from','Status']),row(['---','---','---']),
  row(['**A · The workflow is reproducible**','the published inputs and an empty canvas',
    '**Holds.** `tests/recreate-from-scratch.browser.mjs`, green on both engines']),
  row(['**B · The study is reproducible**','a primary source — the `.osm.pbf` a reader downloads',
    '**Does not hold today**']),'',
  'A is the claim about this application: given the inputs, every widget, parameter and connection',
  'needed is reachable from the palette and the panels. It is proved for one workflow.','',
  'B is the claim about the whole chain, and it fails at **one step, for one reason**:',
  '`geo/thames-reaches.geojson` was SELECTED out of the water areas, and nothing in this',
  'application selects.','',
  'No geometry was cut to make it. The file says so in its own method: *"Nothing is cut at the',
  'limit: OpenStreetMap already divides the water area at the lock, and the two reaches are the',
  'polygons joined to either side of that shared edge."* Both reaches are OpenStreetMap',
  'multipolygons as published, and the clip to the study box is what the extract reader already',
  'does. So a reader starting from the Greater London extract obtains both reaches in the read —',
  'together with every pond, basin and boating lake in the box — and has no way to keep the two',
  'they came for.','',
  'The gap is selection and nothing else. The function already exists one port type over:',
  '`select_rows`, *"Keep only the rows whose key column holds one of the values you name, in that',
  'order"*, which takes a table and emits a table. D2 asks whether a widget already does the job',
  'before another is added, and here one does — for the wrong port type.','',
  '**An input whose provenance is recorded is not the same as an input a practitioner could',
  'produce.** The provenance here is unusually good — the method is in the file, in its own',
  'properties, naming the relations it used. That is what makes the gap visible rather than what',
  'causes it, and it is why B is a question that can be asked at all.','',
  '**What counts as reproducible, and it is not how the project happened to do it.** The',
  'practitioner set the criterion on 2026-10-29, about the water intakes and Teddington Lock:','',
  '> These were obtained directly from John Snow text, and I think that\'s OK, because I could very',
  '> well have used input_points for that with pushpins.','',
  'That is the right test: an input is reproducible when an existing widget could produce it, not',
  'only when it was produced that way. And the pushpin editor does carry what this one needs — it',
  'has a form builder (`pin-field-key`, `pin-field-label`, `pin-field-type`), so the `company`,',
  '`drawn_from`, `in_use` and `snow_says` fields are enterable — checked by a test rather than',
  'read off the markup — and the coordinates are of the',
  'landmarks Snow names rather than a survey nobody can repeat. Transcribing a source text and',
  'placing four pins is a path through this application.','',
  'So claim B, taken input by input for `south-london/ground`:','',
  row(['Input','A practitioner\'s path to it','Status']),row(['---','---','---']),
  row(['32 sub-districts','a published BSD-2 file, downloaded and read by `polygon_input`','Obtainable']),
  row(['Water intakes and the lock','`point_input` pushpins with a form, filled from Snow\'s text',
    '**Producible** — proven, not inspected: a test places four pins, declares a `company` field '
    +'and checks it reached every one']),
  row(['Thames reaches','read the extract, then keep the two reaches out of the water areas',
    '**Blocked** — nothing selects']),'',
  'One input of three, and one capability. What would close B: a way to keep or drop features of a',
  'polygon layer by their attributes or their identifiers. That is all. The two reaches would then',
  'be read, selected and named inside the application, and claim B would hold for this workflow.','',
  '### The pinned example','',
  ...pinned.map(e=>`- \`${(e.id??e.repository).split('/').pop()}\` declares ${(e.uses??[]).length} `
    +`node types. Its inputs are files in its own repository, and \`geo/water-intakes.geojson\` was `
    +`written on 2026-10-29 because those four features existed only inside the bundle until then `
    +`— the one input a reader could not download.`),'');

// 3 · WHAT TO DO ABOUT IT. Generated from the same numbers, so a recommendation cannot outlive
// the gap that produced it: when the count reaches zero the line says so rather than persisting
// as advice nobody rechecked. The practitioner, 2026-10-29: *"we should also generate a list of
// recommendation to address audit gaps."*
//
// Each says what was measured, what closing it would mean, and nothing about whether it is worth
// doing -- that is a decision with a cost, and this file measures.
const carrying=perExample.filter(e=>e.undeclared.length);
const attachedExamples=perExample.filter(e=>e.attachedTypes.length);
const soleHeavy=[...byExample].sort((a,b)=>b[1].length-a[1].length)[0];
const decomposition=['snap_to_network','reachable_nodes','reachable_corridor','travel_time_band'];
const residue=unused.filter(t=>!decomposition.includes(t)&&t!=='micro_workflow');
const recommendations=[
  [`Give the ${totalUndeclared} data-carrying nodes a declared source`,
   `${carrying.length} shipped examples hold ${totalUndeclared} nodes that carry data and name no `
   +`origin: ${carrying.map(e=>`\`${e.key}\` (${e.undeclared.length})`).join(', ')}. Closing it `
   +`means either a \`sourceInfo\`/\`provenance\` block naming where the data came from, or a `
   +`published file beside the example the way \`geo/water-intakes.geojson\` was written on `
   +`2026-10-29. Until then each is a payload a rebuild must copy rather than fetch.`],
  [`Ask D11 of the ${residue.length} widgets no workflow reaches`,
   `${residue.map(t=>`\`${t}\``).join(', ')}. Not a retirement list: D11 asks whether a residual `
   +`function remains that nothing else performs, and a widget may be unreached because no example `
   +`poses its problem. The answer is per widget and this audit does not have it.`],
  [`Settle what a monolith and its decomposition owe each other`,
   `Use propagates from a composition to its members and not from an equivalent monolith, so `
   +`${decomposition.length} widgets read as unreached while a workflow performs their work. It is `
   +`a question about the admission criteria rather than about those widgets, and the count is `
   +`deliberately left as it is until it is answered.`],
  [`Give a second workflow to the widgets one example carries alone`,
   `${soleHeavy?`\`${soleHeavy[0]}\` is the sole evidence for ${soleHeavy[1].length} widgets`:'No example carries a sole-evidence set'}. `
   +`Restructuring an example can take that evidence with it and nothing reports the loss. Closing `
   +`it means a second workflow reaching those widgets, or recording the fragility as accepted.`],
  [`Extend the from-scratch rebuild past one workflow`,
   `\`tests/recreate-from-scratch.browser.mjs\` proves \`south-london/ground\` can be built from `
   +`an empty canvas and published files. The other five South London workflows and all `
   +`${shipped.length} shipped examples are unproven, and it is the only test that can show a `
   +`parameter is reachable from its own panel.`],
  [`Check that a declared source resolves, not only that it exists`,
   `This audit reads whether \`sourceInfo\` or \`provenance\` is present. \`validate:examples\` `
   +`verifies the pinned bundle's per-file digests; nothing verifies a shipped example's declared `
   +`source, so a dead URL or a moved file reads as declared.`],
  ...(attachedExamples.length?[[`Resolve the ${attachedExamples.reduce((n,e)=>n+e.attachedTypes.length,0)} widgets attached to one example`,
   `${attachedExamples.map(e=>`\`${e.key}\`: ${e.attachedTypes.map(t=>`\`${t}\``).join(', ')}`).join('; ')}. `
   +`Each is already carried in \`widgets/standardization.json\` with the record that would remove `
   +`it, and the exemption ceiling may fall and may never rise.`]]:[]),
];
lines.push('## 3 · Recommendations','',
  'Generated from the numbers above, so a recommendation cannot outlive the gap that produced it.',
  'Each says what was measured and what closing it would mean. None says whether it is worth',
  'doing: that is a decision with a cost, and this file measures.','',
  ...recommendations.flatMap(([title,body],i)=>[`**R${i+1}. ${title}.** ${body}`,'']));

const document=lines.join('\n')+'\n';
const path='docs/audits/worked-example-audit.md';
if(process.argv.includes('--write')){
  writeFileSync(`${root}/${path}`,document);
  console.log(`Wrote ${path}`);
}else{
  console.log(`Worked-example audit: ${evidence.widgets.length} widgets, ${shipped.length} shipped `
    +`examples, ${unused.length} widgets no workflow uses, ${totalUndeclared} nodes carrying data `
    +`that declare no source.`);
  const current=(()=>{try{return readFileSync(`${root}/${path}`,'utf8');}catch{return null;}})();
  if(current!==document){
    console.log(`\n${path} is stale. Run: node scripts/audit-worked-examples.mjs --write`);
    process.exitCode=1;
  }
}
