#!/usr/bin/env node
/** Writes the compiled kernel into `src/kernel-bytes.ts`, so loading it needs no path and no fetch:
 *  the same bytes reach the browser, a test and an offline session. `--check` fails if they differ. */
import {readFileSync,writeFileSync} from 'node:fs';
const bytes=readFileSync('kernel/fieldwork-kernel.wasm').toString('base64');
const text=`/** Generated by scripts/embed-kernel.mjs from kernel/fieldwork-kernel.wasm. Do not edit. */\n`
  +`export const KERNEL_BASE64='${bytes}';\n`;
if(process.argv.includes('--check')){
  if(readFileSync('src/kernel-bytes.ts','utf8')!==text){
    console.error('src/kernel-bytes.ts does not match kernel/fieldwork-kernel.wasm. Run: npm run build:kernel');
    process.exit(1);
  }
  console.log('Kernel bytes match the compiled kernel.');
}else writeFileSync('src/kernel-bytes.ts',text);
