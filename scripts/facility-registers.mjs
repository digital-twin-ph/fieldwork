// THE FACILITY REGISTER CATALOGUE, generated from the ontology (experiment 190). The registers are declared once, as
// fw:FacilityRegister individuals in ontology/fieldwork.ttl, so the code and the ontology cannot say different things
// about a register. Usage: node scripts/facility-registers.mjs [--write]; without --write it checks the file is current.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {Parser} from 'n3';

const FW='urn:fieldwork:',RDF='http://www.w3.org/1999/02/22-rdf-syntax-ns#type';
const DCT='http://purl.org/dc/terms/',DCAT='http://www.w3.org/ns/dcat#',OWL='http://www.w3.org/2002/07/owl#';
const root=new URL('../',import.meta.url);
const quads=new Parser().parse(readFileSync(new URL('ontology/fieldwork.ttl',root),'utf8'));
const of=(subject,predicate)=>quads.find(q=>q.subject.value===subject&&q.predicate.value===predicate)?.object.value;
const registers=quads.filter(q=>q.predicate.value===RDF&&q.object.value===FW+'FacilityRegister').map(q=>q.subject.value).sort()
  .map(id=>{
    const field=name=>of(id,FW+name);
    const count=of(id,FW+'registerRecordCount');
    return {id,title:of(id,DCT+'title'),version:of(id,OWL+'versionInfo'),publisher:of(id,DCT+'publisher')??null,
      licence:of(id,DCT+'license'),country:field('countryCode'),url:of(id,DCAT+'accessURL'),
      readable:field('registerReadable')==='true',readOn:field('registerReadOn'),records:count?Number(count):null,
      fields:{name:field('nameField')??null,alternateName:field('alternateNameField')??null,type:field('typeField')??null,
        area:field('areaField')??null,identifier:field('identifierField')??null,latitude:field('latitudeField')??null,
        longitude:field('longitudeField')??null}};
  });
for(const r of registers)if(r.readable&&Object.entries(r.fields).some(([k,v])=>k!=='alternateName'&&!v))
  throw new Error(`${r.id} is marked readable and does not name every field it needs.`);
const text=JSON.stringify({schema:'fieldwork/facility-registers/1',
  note:'Generated by scripts/facility-registers.mjs from the fw:FacilityRegister individuals in ontology/fieldwork.ttl. Do not edit.',
  registers},null,1)+'\n';
const out=new URL('widgets/facility-registers.json',root);
if(process.argv.includes('--write')){writeFileSync(out,text);console.log(`Wrote widgets/facility-registers.json: ${registers.length} registers, ${registers.filter(r=>r.readable).length} readable.`);}
else if(!existsSync(out)||readFileSync(out,'utf8')!==text){console.error('widgets/facility-registers.json has drifted from the ontology. Run: node scripts/facility-registers.mjs --write');process.exit(1);}
else console.log(`Facility registers: ${registers.length} declared in the ontology, catalogue current.`);
