// What each widget's ports actually are, and which of them it insists on.
//
// A widget's contract is assembled at run time from three places: TYPES.inputs (a union across
// alternatives, and incomplete -- 13 widget/port pairs are used by the shipped examples and
// declared nowhere), nodeInputs (resolves it from the node's parameters), and a filter inside
// executionPlan that drops the ports it does not insist on. None of that is declared anywhere a
// rule could read, and only one widget of 45 records `optionalInputs` in its release file.
//
// This derives the declaration FROM the behaviour, so it starts true; validate-port-contracts
// regenerates and fails on drift, so it stays true. Flipping the dependency -- executionPlan
// reading the declaration rather than rebuilding it -- is the step after, and this is what makes
// that step checkable. Experiment 112.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {TYPES,nodeInputs,requiredInputs} from '../build/core.js';

const root=fileURLToPath(new URL('../',import.meta.url));

/** The parameter settings that change a widget's ports, named rather than discovered: nodeInputs
 *  branches on inputMode, source, centers, contextPoints, pointInputCount, ruleset and composition.
 *  A branch added without a variant here produces a contract nothing records, which is the drift
 *  the validator exists to catch. */
export const VARIANTS={
  map_output:[{inputMode:'spatial'},{inputMode:'decisions'},{inputMode:'raster'},
    {inputMode:'polygons'},{inputMode:'polygons',contextPoints:true},{inputMode:'network'}],
  table_output:[{inputMode:'spatial'},{inputMode:'decisions'},{inputMode:'polygons'},{inputMode:'table'}],
  chart_output:[{inputMode:'decisions'},{inputMode:'polygons'},{inputMode:'series'}],
  case_series:[{source:'table'},{source:'points'}],
  compare_point_sets:[{},{centers:true}],
  coverage_check:[{}],
};



const key=params=>Object.keys(params).length?Object.entries(params).sort()
  .map(([k,v])=>`${k}=${v}`).join(','):'default';

export function contracts(){
  const out={};
  for(const [type,definition] of Object.entries(TYPES)){
    if(!definition?.group)continue;
    // apply_ruleset and micro_workflow take their ports from a pinned ruleset or composition, so
    // their contract is that other document's, not theirs. Recorded as deferred rather than empty.
    if(type==='apply_ruleset'||type==='micro_workflow'){
      out[type]={lateBoundTo:type==='apply_ruleset'?'the pinned ruleset\'s inputContract.ports':'the pinned composition\'s ports',contracts:[]};
      continue;
    }
    const variants=VARIANTS[type]??[{}];
    const seen=new Map();
    for(const params of variants){
      const node={id:'n',type,x:0,y:0,params:{label:'x',pointInputCount:1,...params}};
      let all;try{all=nodeInputs(node);}catch{continue;}
      const req=requiredInputs(node).map(([p,t])=>[p,t]);
      const opt=all.filter(([p])=>!req.some(([r])=>r===p)).map(([p,t])=>[p,t]);
      const signature=JSON.stringify([req,opt]);
      if(seen.has(signature))continue;
      seen.set(signature,{when:key(params),required:req,optional:opt});
    }
    out[type]={output:definition.output??null,contracts:[...seen.values()]};
  }
  return out;
}

export const document_=()=>({
  schema:'fieldwork/port-contracts/1',
  note:'GENERATED by scripts/port-contracts.mjs from src/core.ts. What each widget\'s ports are under each parameter setting that changes them, and which of those it insists on before it will run. Derived from the behaviour so it starts true; validate-port-contracts regenerates and fails on drift so it stays true. A widget with several contracts has alternatives selected by a parameter, not a conjunction: a map in polygons mode needs polygons alone, and reading TYPES.inputs as "needs all four" is what made experiment 112 report that a map could never be revealed.',
  generatedAt:new Date().toISOString().slice(0,10),
  widgets:contracts(),
});

if(import.meta.url===`file://${process.argv[1]}`){
  const doc=document_();
  const widgets=Object.entries(doc.widgets);
  if(process.argv.includes('--write')){
    writeFileSync(join(root,'widgets/port-contracts.json'),JSON.stringify(doc,null,2)+'\n');
    console.log('Wrote widgets/port-contracts.json');
  }
  const alternatives=widgets.filter(([,w])=>w.contracts.length>1);
  const optional=widgets.filter(([,w])=>w.contracts.some(c=>c.optional.length));
  console.log(`Port contracts: ${widgets.length} widgets, ${alternatives.length} with alternatives, ${optional.length} with an optional port.`);
  for(const [t,w] of alternatives)console.log(`  ${t}: ${w.contracts.map(c=>c.when).join(' | ')}`);
}
