#!/usr/bin/env node
/** What the version a practitioner is offered today changed, as data the application can show.
 *
 * Every widget release carries `changes` -- 148 descriptions across 147 release files -- and
 * until 2026-10-15 nothing read a single one of them. The same was true of the ruleset layer's
 * change notes, declared 2026-10-12 and inert. The practitioner's instruction: "The widget manual
 * should explain what was changed in the current version, and to warn of deprecated or
 * incompatible functionality."
 *
 * Generated rather than imported, because the 147 release files are not bundled into the browser
 * build and should not be: this writes only the CURRENT release's notes per widget, which is what
 * the instruction asks to be shown. Run `npm run notes:releases`.
 *
 * `breaking` is derived rather than declared, from three signals the releases actually use: a
 * `kind` of major, an explicit `breaking` flag, and a stated `migration`. The kind vocabulary is
 * inconsistent across releases -- initial, baseline, added, changed, enhancement, feature, minor,
 * major, patch, and one entry with no kind at all -- which is recorded here rather than silently
 * normalised, because a warning derived from a vocabulary nobody has agreed is a warning that
 * will be wrong at some point and should be readable when it is.
 *
 * Usage: node scripts/release-notes.mjs [--write]
 */
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const read=path=>JSON.parse(readFileSync(join(root,path),'utf8'));

export function releaseNotes(){
  const registry=read('widgets/registry.json');
  const kinds=new Set();
  const widgets={};
  for(const entry of registry.widgets){
    const release=entry.releases.find(r=>r.version===entry.currentVersion);
    // A BUMPED currentVersion WITH NO RELEASE ENTRY IS A MISTAKE, not a widget to skip. This
    // read `continue`, so bumping table_input to 0.2.0 and forgetting to register the file
    // DELETED it from the notes -- 62 widgets became 61 -- and the validator then agreed with
    // the file it had just generated. Caught on 2026-10-27 only by noticing the count.
    if(!release)throw new Error(`${entry.nodeType} declares currentVersion ${entry.currentVersion} `
      +`and its releases list carries ${entry.releases.map(r=>r.version).join(', ')||'nothing'}. `
      +'Add the release file to widgets/registry.json, with its path and sha256. Skipping it here '
      +'would drop the widget from the release notes and the gate would then check the gap.');
    const file=read(release.path);
    const changes=(file.changes||[]).filter(c=>c&&typeof c==='object').map(change=>{
      if(change.kind)kinds.add(change.kind);
      const breaking=change.kind==='major'||change.breaking===true||!!change.migration;
      return {kind:change.kind||'unstated',description:String(change.description||'').trim(),
        ...(breaking?{breaking:true}:{}),
        ...(change.migration?{migration:String(change.migration)}:{})};
    }).filter(c=>c.description);
    const compatibility=file.compatibility||{};
    widgets[entry.nodeType]={version:entry.currentVersion,released:file.released,changes,
      breaking:changes.some(c=>c.breaking),
      ...(compatibility.migrationFrom?{migrationFrom:compatibility.migrationFrom}:{}),
      ...(compatibility.replacementCandidate?{replacementCandidate:compatibility.replacementCandidate}:{})};
  }
  return {schema:'fieldwork/release-notes/1',
    note:'Generated by scripts/release-notes.mjs from each widget\'s CURRENT release. Do not edit.',
    kindVocabulary:[...kinds].sort(),widgets};
}

const notes=releaseNotes();
const path='widgets/release-notes.json';
const text=JSON.stringify(notes,null,1)+'\n';
if(process.argv.includes('--write')){
  writeFileSync(join(root,path),text);
  const documented=Object.values(notes.widgets).filter(w=>w.changes.length).length;
  const breaking=Object.values(notes.widgets).filter(w=>w.breaking).length;
  console.log(`Wrote ${path}: ${Object.keys(notes.widgets).length} widgets, ${documented} whose current `
    +`release says what it changed, ${breaking} whose current release is breaking. `
    +`Kinds in use: ${notes.kindVocabulary.join(', ')}.`);
}else{
  const current=readFileSync(join(root,path),'utf8');
  if(current!==text){
    console.error(`${path} is out of date with the releases it is generated from. Run npm run notes:releases.`);
    process.exit(1);
  }
  console.log(`${path} matches the current releases of ${Object.keys(notes.widgets).length} widgets.`);
}
