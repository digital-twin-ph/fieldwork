// Generates ontology/widgets.ttl: one individual per registered widget, carrying its label, its
// node type, and -- where a page exists -- fw:userManual pointing at it.
//
// Generated rather than hand-written, because a manual link maintained by hand is a link that
// rots: the page gets renamed and the triple still resolves to nothing. The registry is the list
// of widgets, docs/widgets/ is the list of pages, and this is the join. Run `npm run manual:widgets`.
import {readFileSync,writeFileSync,readdirSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const registry=JSON.parse(readFileSync(join(root,'widgets/registry.json'),'utf8'));
const pagesDir=join(root,'docs/widgets');
export const pages=()=>existsSync(pagesDir)
  ? new Set(readdirSync(pagesDir).filter(f=>f.endsWith('.md')).map(f=>f.replace(/\.md$/,'')))
  : new Set();

/** The widgets a page is owed for, and the ones that have one. */
export function coverage(){
  const have=pages();
  const live=registry.widgets.map(w=>w.nodeType);
  return {live,documented:live.filter(t=>have.has(t)),
    missing:live.filter(t=>!have.has(t)),
    orphaned:[...have].filter(t=>!live.includes(t))};
}

const escape=value=>JSON.stringify(String(value));
const MANUAL_BASE='https://github.com/digital-twin-ph/fieldwork/blob/main/docs/widgets/';
export function turtle(){
  const {live,documented}=coverage();
  // The title a practitioner sees, read from each widget's current release rather than invented
  // here: a label that disagrees with the palette is worse than no label.
  const titles=new Map(registry.widgets.map(w=>{
    const release=w.releases.find(r=>r.version===w.currentVersion);
    const file=JSON.parse(readFileSync(join(root,release.path),'utf8'));
    return [w.nodeType,file.title||w.nodeType];
  }));
  const lines=['@prefix fw: <urn:fieldwork:>.',
    '@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#>.',
    '@prefix owl: <http://www.w3.org/2002/07/owl#>.','',
    '# GENERATED by scripts/widget-manual.mjs from widgets/registry.json and docs/widgets/.',
    '# Do not edit: `npm run manual:widgets` rewrites it and validate:manual fails on drift.','',
    '<urn:fieldwork:ontology:widgets> a owl:Ontology;',
    `  rdfs:comment ${escape('One individual per registered widget, with the page of the distributed user manual that describes it. Generated, so a renamed page cannot leave a triple pointing at nothing.')}.`,''];
  for(const nodeType of live){
    const iri=`<urn:fieldwork:widget:${nodeType}>`;
    lines.push(`${iri} a fw:WidgetDefinition; fw:nodeType ${escape(nodeType)}; rdfs:label ${escape(titles.get(nodeType))}`
      +(documented.includes(nodeType)?`;\n  fw:userManual <${MANUAL_BASE}${nodeType}.md>`:'')+'.');
  }
  return lines.join('\n')+'\n';
}

if(import.meta.url===`file://${process.argv[1]}`){
  const {live,documented,missing,orphaned}=coverage();
  if(process.argv.includes('--write')){
    writeFileSync(join(root,'ontology/widgets.ttl'),turtle());
    writeFileSync(join(root,'widgets/manual-pages.json'),JSON.stringify(compiledPages(),null,2)+'\n');
    console.log('Wrote ontology/widgets.ttl and widgets/manual-pages.json');
  }
  console.log(`Widget manual: ${documented.length} of ${live.length} widgets have a page, ${missing.length} do not.`);
  if(orphaned.length)console.error(`  pages for widgets that are not registered: ${orphaned.join(', ')}`);
  if(missing.length)console.log(`  without a page: ${missing.slice(0,8).join(', ')}${missing.length>8?` and ${missing.length-8} more`:''}`);
  process.exit(orphaned.length?1:0);
}

/** The pages, compiled to HTML at build time.
 *
 *  Compiled rather than parsed in the browser: there is no markdown renderer in this project's
 *  dependencies, and adding one to render six files we wrote ourselves would be a runtime cost and
 *  a supply-chain one for no gain. The subset is what the pages actually use -- headings, lists,
 *  tables, paragraphs, bold, code, links -- and anything outside it is left as text rather than
 *  guessed at. Every value is escaped before any markup is added, so a page cannot inject HTML. */
function esc(t){return t.replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'})[c]);}
function inline(t){return esc(t)
  .replace(/`([^`]+)`/g,'<code>$1</code>')
  .replace(/\*\*([^*]+)\*\*/g,'<strong>$1</strong>')
  .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g,'<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>');}

export function toHTML(markdown){
  const out=[];let list=null,table=null,para=[];
  const closeList=()=>{if(list){out.push(`</${list}>`);list=null;}};
  const closeTable=()=>{if(table){out.push('</tbody></table>');table=null;}};
  // Markdown joins consecutive non-blank lines into ONE paragraph. Emitting a <p> per source line
  // broke every wrapped sentence in half, which is what hard-wrapped prose looks like if you
  // forget that the line breaks are not in the document.
  const closePara=()=>{if(para.length){out.push(`<p>${inline(para.join(' '))}</p>`);para=[];}};
  for(const raw of markdown.split('\n')){
    const line=raw.trimEnd();
    if(!line.trim()){closePara();closeList();closeTable();continue;}
    const heading=/^(#{1,4})\s+(.*)$/.exec(line);
    if(heading){closePara();closeList();closeTable();const level=heading[1].length+1;out.push(`<h${level}>${inline(heading[2])}</h${level}>`);continue;}
    if(/^\|/.test(line)){
      closePara();closeList();
      const cells=line.split('|').slice(1,-1).map(c=>c.trim());
      if(cells.every(c=>/^-+$/.test(c.replace(/:/g,''))))continue;   // the --- separator row
      if(!table){table='head';out.push('<table><thead><tr>'+cells.map(c=>`<th>${inline(c)}</th>`).join('')+'</tr></thead><tbody>');continue;}
      out.push('<tr>'+cells.map(c=>`<td>${inline(c)}</td>`).join('')+'</tr>');continue;
    }
    const item=/^[-*]\s+(.*)$/.exec(line);
    if(item){closePara();closeTable();if(!list){list='ul';out.push('<ul>');}out.push(`<li>${inline(item[1])}</li>`);continue;}
    closeList();closeTable();
    para.push(line.trim());
  }
  closePara();closeList();closeTable();
  return out.join('');
}

export function compiledPages(){
  const {documented}=coverage();
  return Object.fromEntries(documented.map(nodeType=>
    [nodeType,toHTML(readFileSync(join(root,`docs/widgets/${nodeType}.md`),'utf8'))]));
}
