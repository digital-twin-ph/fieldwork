import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';
import {sourceDefinitions} from './validate-widgets.mjs';

// The human half of the naming gate. scripts/validate-naming.mjs checks the six rules that can be
// mechanised; "name the operation in the words a practitioner would use to ask for it" cannot be,
// and that is the rule that matters most. So the names are published in one table a practitioner
// can read -- node type beside the words the palette actually shows -- and every live widget must
// carry a review verdict in widgets/name-review.json.
//
// The table is generated, never hand-edited: a second hand-maintained list of names would drift
// from the definitions, which is the defect that put three slr_ widgets in a list whose own
// comment says it is for widgets that apply to any domain.

const root=fileURLToPath(new URL('../',import.meta.url));
const read=path=>JSON.parse(readFileSync(root+path,'utf8'));

/** What a reviewer is judging: the identifier, the words shown in the palette, and the place in
 *  the palette those words appear under. A review is only valid for the three together, so it is
 *  pinned to their digest -- change any one and the review goes stale rather than silently
 *  carrying over. */
export const fingerprint=row=>createHash('sha256')
  .update(`${row.nodeType}\n${row.title}\n${row.group}`).digest('hex').slice(0,12);

export async function palette(){
  const result=await build({absWorkingDir:root,entryPoints:['src/palette.ts'],bundle:true,
    write:false,platform:'node',format:'esm'});
  return import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
}

export function rows({definitions,classification,palette:p}){
  const byType=Object.fromEntries(classification.widgets.map(w=>[w.nodeType,w]));
  const inputStage=new Set(p.INPUT_STAGE);
  const viaComposition=new Set([...p.ADDABLE_VIA_COMPOSITION,...p.ADDABLE_VIA_RULESET]);
  const order=p.PALETTE_GROUPS;
  return Object.entries(definitions)
    .filter(([type])=>!byType[type]?.retired)
    .map(([nodeType,definition])=>{
      // Where a practitioner meets it, derived from the one gate rather than from a list. The
      // fourth value here was 'example templates only', and it reported nine widgets for weeks
      // before anyone read it as a defect; there is no longer a state it can describe.
      const offered=viaComposition.has(nodeType)?'via a composition or ruleset'
        :inputStage.has(nodeType)?'input stage, offered first'
        :'once the canvas holds an input';
      const row={nodeType,title:definition.title,group:definition.group,
        classification:byType[nodeType]?.classification??'unclassified',
        pack:byType[nodeType]?.pack??null,offered,
        ports:(definition.inputs??[]).map(([port,portType])=>`${port}:${portType}`).join(', ')||'none',
        output:definition.output??'none'};
      return {...row,fingerprint:fingerprint(row)};
    })
    .sort((a,b)=>order.indexOf(a.group)-order.indexOf(b.group)||a.nodeType.localeCompare(b.nodeType));
}

const VERDICTS=['accepted','flagged','pending'];

export function markdown({rows,review,stampedAt}){
  const byType=Object.fromEntries((review.reviews??[]).map(r=>[r.nodeType,r]));
  const mark=row=>{
    const entry=byType[row.nodeType];
    if(!entry)return 'never reviewed';
    if(entry.fingerprint!==row.fingerprint)return `stale (${entry.verdict})`;
    return entry.verdict==='flagged'?`**flagged** — ${entry.note}`:entry.verdict;
  };
  const counts=Object.fromEntries(VERDICTS.map(v=>[v,rows.filter(r=>byType[r.nodeType]?.verdict===v
    &&byType[r.nodeType]?.fingerprint===r.fingerprint).length]));
  const groups=[...new Set(rows.map(r=>r.group))];
  // The repository's doc stamp, so this file is held to the same date discipline as every other
  // document rather than exempted for being generated. `created` is fixed at the date the gate was
  // added and `updated` moves with the ledger's stampedAt.
  let out=`# Widget names, for review\n\n_Created 2026-10-13 · Updated ${stampedAt}_\n\n`
    +`_Generated by \`npm run names:widgets\`. `
    +`Do not edit this file: it is built from \`src/core.ts\`, \`src/palette.ts\` and `
    +`\`widgets/classification.json\`, and \`npm run validate:names\` fails if it has drifted._\n\n`
    +`**Review this table.** The middle column is the words the palette shows a practitioner; the `
    +`first is the identifier saved workflows carry. Where they disagree, or where the words are `
    +`not what you would say to ask for the operation, record it in \`widgets/name-review.json\` `
    +`with \`"verdict": "flagged"\` and a note, and it will appear here and in the build output `
    +`until it is resolved.\n\n`
    +`${rows.length} live widgets · ${counts.accepted} accepted · ${counts.flagged} flagged · `
    +`${counts.pending} awaiting review · `
    +`${rows.filter(r=>!byType[r.nodeType]||byType[r.nodeType].fingerprint!==r.fingerprint).length} `
    +`never reviewed or stale\n`;
  for(const group of groups){
    out+=`\n## ${group}\n\n| Node type | Shown in the palette as | Kind | Offered | Ports | Review |\n`
      +`| --- | --- | --- | --- | --- | --- |\n`;
    for(const row of rows.filter(r=>r.group===group))
      out+=`| \`${row.nodeType}\` | ${row.title} | ${row.classification}`
        +`${row.pack?` · ${row.pack.split(':').pop()}`:''} | ${row.offered} `
        +`| ${row.ports} → ${row.output} | ${mark(row)} |\n`;
  }
  const flagged=rows.filter(r=>byType[r.nodeType]?.verdict==='flagged');
  if(flagged.length){
    out+=`\n## Flagged names\n\nRaised in review and not yet resolved.\n\n`;
    for(const row of flagged)
      out+=`- \`${row.nodeType}\` (“${row.title}”) — ${byType[row.nodeType].note}`
        +`${byType[row.nodeType].reviewedBy?` _(${byType[row.nodeType].reviewedBy}, ${byType[row.nodeType].reviewed})_`:''}\n`;
  }
  return out;
}

export async function table(){
  const [{definitions},p]=await Promise.all([sourceDefinitions(),palette()]);
  return {rows:rows({definitions,classification:read('widgets/classification.json'),palette:p}),
    review:read('widgets/name-review.json')};
}

if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  const {rows:list,review}=await table();
  const path=root+'docs/widget-names.md';
  const stampedAt=review.stampedAt??new Date().toISOString().slice(0,10);
  const text=markdown({rows:list,review,stampedAt});
  if(process.argv.includes('--write')){writeFileSync(path,text);console.log(`Wrote docs/widget-names.md (${list.length} widgets).`);}
  else{
    const current=readFileSync(path,'utf8');
    if(current!==text){
      console.error('docs/widget-names.md has drifted from the definitions. Run `npm run names:widgets`.');
      process.exit(1);
    }
    console.log(`docs/widget-names.md matches the definitions (${list.length} widgets).`);
  }
}
