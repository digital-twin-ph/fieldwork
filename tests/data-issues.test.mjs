/** EXPERIMENT 207: every kind of data issue the code can report is declared in the FW ontology (ontology/fieldwork.ttl),
 *  with the label the screen shows and the dimension it measures; and an issue in a receipt is about the data. */
const quads=new Parser().parse(readFileSync(new URL('../ontology/fieldwork.ttl',import.meta.url),'utf8'));
const DQV='http://www.w3.org/ns/dqv#';
const FW='urn:fieldwork:',SKOS='http://www.w3.org/2004/02/skos/core#';
const of=(s,p)=>quads.filter(q=>q.subject.value===s&&q.predicate.value===p).map(q=>q.object.value);

test('every kind the code reports is declared, labelled as the screen labels it, and placed in a dimension',()=>{
  for(const [kind,label] of Object.entries(ISSUE_LABEL)){
    assert.deepEqual(of(FW+kind,SKOS+'prefLabel'),[label],`${kind}'s label`);
    assert.equal(of(FW+kind,DQV+'inDimension').length,1,`${kind} measures one dimension`);
    assert.ok(of(FW+kind,SKOS+'inScheme').includes(FW+'dataIssueKinds'),`${kind} is in the scheme`);
  }
});

test('an issue in a receipt is about the data: computed on it, listed by it, generated by the step that found it',()=>{
  const data='<urn:fieldwork:run:r:output:list>',step='<urn:fieldwork:run:r:ruleset:s>';
  const n3=issueFacts(step,data,'urn:fieldwork:run:r:ruleset:s',[{kind:'ValueAbsent',column:'dt_onset',count:27,of:162,says:'27 of 162 have no onset.'}]);
  const got=new Parser().parse(n3);
  const issue=got.find(q=>q.predicate.value===DQV+'hasQualityMeasurement');
  assert.equal(issue.subject.value,'urn:fieldwork:run:r:output:list','the data lists the issue');
  const about=p=>got.find(q=>q.subject.equals(issue.object)&&q.predicate.value===p)?.object.value;
  assert.equal(about('http://www.w3.org/1999/02/22-rdf-syntax-ns#type'),FW+'DataIssue');
  assert.equal(about(DQV+'computedOn'),'urn:fieldwork:run:r:output:list');
  assert.equal(about('http://www.w3.org/ns/prov#wasGeneratedBy'),'urn:fieldwork:run:r:ruleset:s');
  assert.equal(about(DQV+'isMeasurementOf'),FW+'ValueAbsent');
  assert.equal(about(FW+'issueColumn'),'dt_onset');
  assert.equal(about(FW+'affectedRecordCount'),'27');
  assert.equal(about(FW+'consideredRecordCount'),'162');
  assert.equal(about('http://www.w3.org/2000/01/rdf-schema#comment'),'27 of 162 have no onset.');
  assert.equal(issueFacts(step,data,'x',[]),'');
});

test('a column no record carries is one finding, Field missing, not a missing value in every record',async()=>{
  const {authoredDataIssues}=await import('../build/authored-application.js');
  const table={kind:'data-table',keys:['id','dt_onset'],valueField:'n',rowCount:3,missingValueCount:0,
    rows:[{key:{id:'a',dt_onset:'2015-05-11'},value:1},{key:{id:'b',dt_onset:''},value:1},{key:{id:'c',dt_onset:'2015-05-20'},value:1}]};
  const issues=authoredDataIssues(table,[{attribute:'dt_onset',predicate:'fw:emergenceDate',kind:'date',label:'Emergence'},
    {attribute:'early_response_date',predicate:'fw:responseCompleteDate',kind:'date',label:'Early response complete'}]);
  assert.deepEqual(issues.map(i=>[i.field,i.why,i.count,i.of]),[['dt_onset','missing',1,3],['early_response_date','absent',3,3]]);
  assert.match(issues[1].says,/no column early_response_date/);
});

/** NO COUNT OF RECORDS EXCEEDS THE RECORDS (2026-11-12). MERS's warning read "189 records the rules could not read" of
 *  162: 27 cases with no onset added to 162 with no response date. Prevented three ways, each tested here. */
test('records touched by several issues are counted once: MERS, 27 without onset and all 162 without a response date',async()=>{
  const {unreadHeadline,recordsAffected}=await import('../build/data-issues.js');
  const all=Array.from({length:162},(_,i)=>i);
  const issues=[{field:'dt_onset',count:27,of:162,records:all.slice(0,27)},{field:'early_response_date',count:162,of:162,records:all}];
  assert.equal(recordsAffected(issues),162);
  assert.equal(unreadHeadline(issues),'162 of 162 records the rules could not read in full, in 2 columns');
  assert.equal(unreadHeadline(issues.slice(0,1)),'27 of 162 records the rules could not read');
  // Two columns missing on overlapping records: 3 and 2 records, 1 in both, are 4 records.
  assert.equal(recordsAffected([{records:[0,1,2]},{records:[2,3]}]),4);
  assert.throws(()=>unreadHeadline([{field:'a',count:2,of:2,records:[0,1]},{field:'b',count:2,of:2,records:[2,3]}]),/cannot exceed/);
});

