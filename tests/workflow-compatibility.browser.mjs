import {test,expect} from '@playwright/test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {collectPageErrors} from './page-errors.mjs';

const fixture=JSON.parse(await readFile(new URL('./fixtures/coverage-workflow-2026-10-05.json',import.meta.url),'utf8'));
// The fixture holds a two-layer `coverage_check`, a shape that stopped existing on 2026-10-21
// when the widget was retired: one clip takes one layer, so a two-layer check is refused by name
// rather than rewritten. These tests are about what ELSE a v1 file must survive, so they use the
// single-layer form; the refusal itself is asserted at the end of this file.
const singleLayer=()=>{
  const w=structuredClone(fixture);
  w.edges=w.edges.filter(e=>e.port!=='points_2');
  w.nodes=w.nodes.filter(n=>n.id!=='second');
  delete w.nodes.find(n=>n.id==='coverage').params.pointInputCount;
  return w;
};
const saved=page=>page.evaluate(()=>JSON.parse(localStorage.getItem('fieldwork-workflow-v1')));
const upload=(page,w)=>page.locator('#workflow-file').setInputFiles({name:'compatibility.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(w))});
const run=async page=>{await page.locator('#run-button').click();await expect(page.locator('#workflow-state')).toHaveText('✓ Run complete',{timeout:45000});};
const receipt=async page=>{
  await page.locator('[data-view="rules"]').click();
  const download=page.waitForEvent('download');await page.locator('#download-evidence').click();
  return JSON.parse(await readFile(await (await download).path(),'utf8'));
};

test('frozen workflow restores typed data, area enrichment and real EYE decisions offline',async({page,context})=>{
  const errors=collectPageErrors(page);
  await page.goto('/?example=blank');await upload(page,singleLayer());await run(page);
  const before=await saved(page),evidence=await receipt(page),map=evidence.outputs.find(o=>o.nodeId==='map');
  // The clip passes on what is inside and carries what it set aside, which the map draws. The
  // review decisions in this list were the coverage check's and went with it.
  assert.deepEqual(map.rows.map(r=>[r.sourceNodeId,r.recordId,r.relation]),[
    ['observations','inside','Inside'],['observations','edge','Boundary'],
    ['observations','outside','Outside'],['observations','missing','MissingLocation'],
  ]);
  assert.deepEqual(map.boundary,fixture.nodes[0].params.geometry);
  assert.equal(map.spatialReference.geometryCRS,'OGC:CRS84');
  // Independent spherical-rectangle reference, not a snapshot generated by the area implementation.
  const rad=Math.PI/180,expected=6371008.8**2*(.02*rad)*Math.abs(Math.sin(-24.68*rad)-Math.sin(-24.7*rad));
  assert.ok(Math.abs(map.measurement.squareMetres-expected)/expected<1e-9);
  // The migrated node keeps its id: the file said `coverage`, and a rewrite that renamed nodes
  // would break every edge and every reference pointing at it.
  const clipFacts=evidence.receipts.find(r=>r.nodeId==='coverage').input;
  for(const token of ['fw:PointInPolygonClip','geo:hasMetricArea','sfWithin'])assert.ok(clipFacts.includes(token),token);
  const mapFacts=evidence.receipts.find(r=>r.nodeId==='map').input;
  assert.ok(mapFacts.includes('geo:sfDisjoint'),'the map says how each point stands to the area');
  // The TYPED attributes of a v1 file must survive it, wherever in the run they are asserted. The
  // retired coverage check wrote them into its own receipt; the point input and the table write
  // them now, so the property is checked across the run rather than in one widget's facts.
  const everything=[evidence.provenanceN3,...evidence.receipts.map(r=>r.input||'')].join('\n');
  for(const token of ['XMLSchema#date','XMLSchema#integer'])assert.ok(everything.includes(token),token);
  await expect(page.locator('#offline-status')).toContainText('Available offline');
  await context.setOffline(true);await page.reload();
  await expect(page.locator('#workflow-state')).toHaveText('✓ Run complete',{timeout:45000});
  assert.deepEqual(await saved(page),before);
  const restored=(await receipt(page)).outputs.find(o=>o.nodeId==='map');
  assert.deepEqual(restored.rows,map.rows);assert.deepEqual(restored.measurement,map.measurement);
  assert.deepEqual(errors,[]);
});

test('rejected imports leave the current workflow and completed results intact',async({page})=>{
  await page.goto('/?example=blank');await upload(page,singleLayer());await run(page);
  const before=await saved(page);
  for(const [mutate,message] of [
    [w=>{w.schema='unknown';},'Invalid Fieldwork workflow'],
    [w=>{w.nodes.find(n=>n.id==='observations').params.data.features[0].properties.household_size='five';},'data type integer'],
    [w=>{w.nodes[0].params.spatialReference={datum:'WGS84',geodeticCRS:'EPSG:3857',geometryCRS:'EPSG:3857',axisOrder:'x-y',units:'metre'};},'CRS'],
    [w=>{w.edges.find(e=>e.to==='map').port='area';},'Incompatible node connection'],
  ]){
    // Mutating the SINGLE-layer form, so each refusal is the one under test rather than the
    // retired widget's layer-count refusal arriving first.
    const invalid=singleLayer();mutate(invalid);await upload(page,invalid);
    await expect(page.locator('#toast')).toContainText(message);
    assert.deepEqual(await saved(page),before);
    await expect(page.locator('#workflow-state')).toHaveText('✓ Run complete');
  await page.locator('[data-view="results"]').click();
    await expect(page.getByRole('tab',{name:'Regression map'})).toBeVisible();
  }
});

test('all eight point inputs remain connectable and survive removal and Undo',async({page})=>{
  // Written against `coverage_check`'s expandable ports; it was retired on 2026-10-21 and the
  // same ports are `map_output`'s. The subject is the port machinery -- eight slots, each
  // connectable, with hit areas that do not overlap, surviving removal and Undo.
  const w=structuredClone(fixture),source=w.nodes.find(n=>n.id==='observations');
  w.nodes=w.nodes.filter(n=>['scope','observations','map'].includes(n.id));
  w.nodes.find(n=>n.id==='map').params={label:'Layers',pointInputCount:1};
  for(let i=2;i<=8;i++)w.nodes.push({...structuredClone(source),id:`layer${i}`,x:40,y:230,params:{...structuredClone(source.params),label:`Layer ${i}`}});
  w.edges=[{id:'area',from:'scope',to:'map',port:'area'},{id:'points',from:'observations',to:'map',port:'points'}];
  await page.goto('/?example=blank');await upload(page,w);
  await page.locator('[data-view="workflow"]').click();
  await page.locator('.react-flow__node[data-id="map"]').click();
  // The configurable port opens the next slot itself when the current one is taken, which is how
  // a practitioner adds a layer; `#add-point-input` is the explicit form of the same thing.
  for(let i=2;i<=8;i++){
    await page.locator('#map-add-layer').selectOption(`layer${i}`);
  await page.locator('[data-view="workflow"]').click();
    await expect(page.locator(`.react-flow__node[data-id="map"] [data-handleid="points_${i}"]`)).toBeVisible();
    await expect(page.locator(`#map-points_${i}`)).toHaveValue(`layer${i}`);
  }
  await expect(page.locator('#add-point-input')).toBeDisabled();
  const handles=page.locator('.react-flow__node[data-id="map"] .react-flow__handle.target');
  const boxes=await handles.evaluateAll(els=>els.map(e=>{const r=e.getBoundingClientRect();return {top:r.top,bottom:r.bottom};}));
  for(let i=1;i<boxes.length;i++)assert.ok(boxes[i].top>boxes[i-1].bottom,'Expandable input hit areas must not overlap');
  await page.locator('#remove-point-input').click();
  assert.equal((await saved(page)).edges.some(e=>e.port==='points_8'),false);
  await page.locator('#undo-button').click();await expect(page.locator('#map-points_8')).toHaveValue('layer8');
  await run(page);const result=(await receipt(page)).outputs.find(o=>o.nodeId==='map');
  assert.equal(result.rows.length,32);assert.equal(result.pointLayers.length,8);
});
